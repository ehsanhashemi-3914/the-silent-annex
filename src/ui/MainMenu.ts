import { button, el } from './dom';
import type { Screen } from './UIManager';

export interface MainMenuActions {
  canContinue(): boolean;
  storageWarning(): boolean;
  continueGame(): void;
  newGame(): void;
  loadGame(): void;
  settings(): void;
  credits(): void;
}

function signalLine(): SVGSVGElement {
  // A hand-drawn-looking trace of the carrier wave. It settles to flat in the centre.
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('class', 'signal-line');
  svg.setAttribute('viewBox', '0 0 360 24');
  svg.setAttribute('preserveAspectRatio', 'none');
  let d = 'M0 12';
  for (let x = 2; x <= 360; x += 2) {
    const envelope = Math.abs(x - 170) / 170;
    const y = 12 + Math.sin(x * 0.34) * Math.sin(x * 0.043) * 9 * envelope * envelope;
    d += ` L${x} ${y.toFixed(1)}`;
  }
  const path = document.createElementNS('http://www.w3.org/2000/svg', 'path');
  path.setAttribute('d', d);
  svg.append(path);
  return svg;
}

export class MainMenu implements Screen {
  readonly root: HTMLElement;
  readonly dismissible = false;
  private continueButton: HTMLButtonElement;
  private loadButton: HTMLButtonElement;
  private hint: HTMLElement;

  constructor(private actions: MainMenuActions) {
    this.root = el('div', 'screen menu-screen');
    const title = el('h1', 'game-title', [el('small', '', 'Hollin Ridge, December 1987'), 'The Silent', el('br'), 'Annex']);
    this.continueButton = button('menu-item', 'Continue', () => actions.continueGame());
    this.loadButton = button('menu-item', 'Load Game', () => actions.loadGame());
    this.hint = el('div', 'menu-hint');
    const list = el('nav', 'menu-list', [
      this.continueButton,
      button('menu-item', 'New Game', () => actions.newGame()),
      this.loadButton,
      button('menu-item', 'Settings', () => actions.settings()),
      button('menu-item', 'Credits', () => actions.credits()),
    ]);
    this.root.append(title, signalLine(), list, this.hint, el('div', 'menu-footer', 'Best played in the dark, with headphones'));
  }

  onOpen(): void {
    this.refresh();
  }

  refresh(): void {
    const canContinue = this.actions.canContinue();
    this.continueButton.disabled = !canContinue;
    this.loadButton.disabled = !canContinue;
    this.hint.textContent = this.actions.storageWarning() ? 'Browser storage is unavailable, so progress will not be kept after closing this page.' : '';
  }
}

